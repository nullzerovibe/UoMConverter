namespace UoMConverter.Generator.Modules.Units;

using System.Text;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Globalization;
using System.Text.RegularExpressions;
using System;

/// <summary>
/// Orchestrates the rendering of C# source code from unit definitions.
/// Handles template generation for individual quantities and the central registry.
/// </summary>
internal static class SourceRenderer {
    private const string AutoGeneratedHeader = "// <auto-generated/>";
    private const char NL = '\n';

    // WARN: Must match the separators parsed by UoMRegistry.LoadQuantity in the library.
    private const char FieldSeparator = '\u001F';
    private const char UnitSeparator = '\u001E';
    private const char ListSeparator = '\u001D';
    private const string FieldSeparatorEscape = "\\u001F";
    private const string UnitSeparatorEscape = "\\u001E";
    private const string ListSeparatorEscape = "\\u001D";

    private sealed class UnitTable {
        public List<string> Records { get; } = [];
        public List<double> Factors { get; } = [];
        public List<double> Offsets { get; } = [];
        public List<(int Index, string ToBase, string FromBase)> NonLinear { get; } = [];
    }

    /// <summary>
    /// Renders a partial class file for a specific physical quantity as compact data (a packed unit table plus factor/offset spans).
    /// </summary>
    /// <remarks>
    /// WHY: Emitting one <c>new Unit(...)</c> per unit produced ~1,800 call sites whose JIT cost dominated cold start (~90 ms).
    /// Constant <c>ReadOnlySpan&lt;double&gt;</c> arguments compile to assembly data, and a single loader loop parses the table.
    /// </remarks>
    public static string RenderQuantityFile(ConfigQuantity quantity, List<RenderDiagnostic> diagnostics) {
        var table = new UnitTable();
        CollectUnits(table, quantity, diagnostics);

        var dimensions = string.Join(";", quantity.BaseDimensions?.Select(d => $"{d.Key}={d.Value}") ?? []);
        var nonLinear = string.Join(", ", table.NonLinear.Select(n => $"({n.Index}, static val => {n.ToBase}, static val => {n.FromBase})"));

        var sb = new StringBuilder();
        sb.Append(AutoGeneratedHeader).Append(NL);
        sb.Append(NL);
        sb.Append("namespace UoMConverter;").Append(NL);
        sb.Append(NL);
        sb.Append("public static partial class UoMRegistry {").Append(NL);
        sb.Append($"    private static void Load{quantity.Name}() => LoadQuantity(").Append(NL);
        sb.Append($"        name: {Literal(quantity.Name)},").Append(NL);
        sb.Append($"        baseUnit: {Literal(quantity.BaseUnit)},").Append(NL);
        sb.Append($"        description: {Literal(quantity.XmlDocSummary)},").Append(NL);
        sb.Append($"        obsoleteText: {NullableLiteral(quantity.ObsoleteText)},").Append(NL);
        sb.Append($"        isLogarithmic: {(quantity.IsLogarithmic ? "true" : "false")},").Append(NL);
        sb.Append($"        scalingFactor: {Number(quantity.ScalingFactor)},").Append(NL);
        sb.Append($"        dimensions: {Literal(dimensions)},").Append(NL);
        sb.Append($"        units: \"{string.Join(UnitSeparatorEscape, table.Records)}\",").Append(NL);
        sb.Append($"        factors: [{string.Join(", ", table.Factors.Select(Number))}],").Append(NL);
        sb.Append($"        offsets: [{string.Join(", ", table.Offsets.Select(Number))}],").Append(NL);
        sb.Append($"        nonLinear: [{nonLinear}]);").Append(NL);
        sb.Append('}').Append(NL);

        return sb.ToString();
    }

    public static string RenderRegistryFile(List<ConfigQuantity> quantities) {
        var sb = new StringBuilder();
        sb.Append(AutoGeneratedHeader).Append(NL);
        sb.Append("using System;").Append(NL);
        sb.Append("using System.Collections.Generic;").Append(NL);
        sb.Append("using System.Collections.Frozen;").Append(NL);
        sb.Append("using System.Collections.Immutable;").Append(NL);
        sb.Append(NL);
        sb.Append("namespace UoMConverter;").Append(NL);
        sb.Append(NL);
        sb.Append("/// <summary>").Append(NL);
        sb.Append("/// Central registry for all physical quantities and units.").Append(NL);
        sb.Append("/// </summary>").Append(NL);
        sb.Append("public static partial class UoMRegistry {").Append(NL);
        sb.Append("    private static readonly Dictionary<string, Quantity> _quantities = new(StringComparer.OrdinalIgnoreCase);").Append(NL);
        sb.Append("    private static readonly Dictionary<string, (Quantity Q, Unit U)> _unitLookupBuilder = new(StringComparer.OrdinalIgnoreCase);").Append(NL);
        sb.Append("    private static readonly Dictionary<string, (Quantity Q, Unit U)> _exactNameLookupBuilder = new(StringComparer.OrdinalIgnoreCase);").Append(NL);
        sb.Append("    private static readonly Dictionary<string, (Quantity Q, Unit U)> _abbreviationLookupBuilder = new(StringComparer.Ordinal);").Append(NL);
        sb.Append(NL);
        sb.Append("    /// <summary>").Append(NL);
        sb.Append("    /// Gets all registered physical quantities keyed by their name.").Append(NL);
        sb.Append("    /// </summary>").Append(NL);
        sb.Append("    public static IReadOnlyDictionary<string, Quantity> Quantities { get; private set; } = FrozenDictionary<string, Quantity>.Empty;").Append(NL);
        sb.Append("    /// <summary>").Append(NL);
        sb.Append("    /// Gets a lookup of units by name or abbreviation (case-insensitive).").Append(NL);
        sb.Append("    /// </summary>").Append(NL);
        sb.Append("    public static FrozenDictionary<string, (Quantity Q, Unit U)> UnitLookup { get; private set; } = FrozenDictionary<string, (Quantity, Unit)>.Empty;").Append(NL);
        sb.Append("    /// <summary>").Append(NL);
        sb.Append("    /// Gets a lookup of units by singular or plural name only (case-insensitive). Takes priority over <see cref=\"UnitLookup\"/>.").Append(NL);
        sb.Append("    /// </summary>").Append(NL);
        sb.Append("    public static FrozenDictionary<string, (Quantity Q, Unit U)> ExactNameLookup { get; private set; } = FrozenDictionary<string, (Quantity, Unit)>.Empty;").Append(NL);
        sb.Append("    /// <summary>").Append(NL);
        sb.Append("    /// Gets a lookup of units by abbreviation (case-sensitive, e.g. 'mW' vs 'MW').").Append(NL);
        sb.Append("    /// </summary>").Append(NL);
        sb.Append("    public static FrozenDictionary<string, (Quantity Q, Unit U)> AbbreviationLookup { get; private set; } = FrozenDictionary<string, (Quantity, Unit)>.Empty;").Append(NL);
        sb.Append(NL);
        sb.Append("    static UoMRegistry() {").Append(NL);

        foreach (var quantity in quantities) {
            sb.Append($"        Load{quantity.Name}();").Append(NL);
        }

        sb.Append("        Quantities = _quantities.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);").Append(NL);
        sb.Append("        UnitLookup = _unitLookupBuilder.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);").Append(NL);
        sb.Append("        ExactNameLookup = _exactNameLookupBuilder.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);").Append(NL);
        sb.Append("        AbbreviationLookup = _abbreviationLookupBuilder.ToFrozenDictionary(StringComparer.Ordinal);").Append(NL);
        sb.Append("    }").Append(NL);
        sb.Append(NL);
        sb.Append("    private static void RegisterUnit(Quantity q, Unit u) {").Append(NL);
        sb.Append("        var entry = (q, u);").Append(NL);
        sb.Append("        _exactNameLookupBuilder.TryAdd(u.SingularName, entry);").Append(NL);
        sb.Append("        _unitLookupBuilder.TryAdd(u.SingularName, entry);").Append(NL);
        sb.Append("        if (!string.Equals(u.SingularName, u.PluralName, StringComparison.OrdinalIgnoreCase)) {").Append(NL);
        sb.Append("            _exactNameLookupBuilder.TryAdd(u.PluralName, entry);").Append(NL);
        sb.Append("            _unitLookupBuilder.TryAdd(u.PluralName, entry);").Append(NL);
        sb.Append("        }").Append(NL);
        sb.Append("        foreach (var abbr in u.Abbreviations) {").Append(NL);
        sb.Append("            _unitLookupBuilder.TryAdd(abbr, entry);").Append(NL);
        sb.Append("            _abbreviationLookupBuilder.TryAdd(abbr, entry);").Append(NL);
        sb.Append("        }").Append(NL);
        sb.Append("    }").Append(NL);
        sb.Append('}').Append(NL);

        return sb.ToString();
    }

    private static void CollectUnits(UnitTable table, ConfigQuantity quantity, List<RenderDiagnostic> diagnostics) {
        var safeName = quantity.Name;

        if (quantity.Units != null) {
            foreach (var unit in quantity.Units) {
                if (unit.SkipConversionGeneration) continue;

                if (!AddUnit(table, safeName, unit, diagnostics)) continue;

                if (unit.Prefixes != null) {
                    foreach (var prefix in unit.Prefixes) {
                        if (PrefixConstants.SIPrefixes.TryGetValue(prefix, out var info) || PrefixConstants.BinaryPrefixes.TryGetValue(prefix, out info)) {
                            var prefixedUnit = new ConfigUnit {
                                SingularName = PrefixedName(prefix, unit.SingularName),
                                PluralName = PrefixedName(prefix, unit.PluralName),
                                FromUnitToBaseFunc = unit.FromUnitToBaseFunc,
                                FromBaseToUnitFunc = unit.FromBaseToUnitFunc,
                                Localization = unit.Localization?.Select(loc => {
                                    var abbrs = new List<string>();
                                    // Check if there's an explicit override for this prefix
                                    if (loc.AbbreviationsForPrefixes != null && loc.AbbreviationsForPrefixes.TryGetValue(prefix, out var element)) {
                                        if (element.ValueKind == JsonValueKind.Array) {
                                            abbrs.AddRange(element.EnumerateArray().Select(e => e.GetString() ?? ""));
                                        }
                                        else if (element.ValueKind == JsonValueKind.String) {
                                            abbrs.Add(element.GetString() ?? "");
                                        }
                                    }
                                    else {
                                        abbrs.AddRange(loc.Abbreviations.Select(abbr => $"{info.symbol}{abbr}"));
                                    }
                                    return new ConfigLocalization {
                                        Culture = loc.Culture,
                                        Abbreviations = abbrs
                                    };
                                }).ToList(),
                                XmlDocSummary = $"Represents the {prefix} prefix of {unit.SingularName}.",
                                ObsoleteText = unit.ObsoleteText
                            };
                            AddUnit(table, safeName, prefixedUnit, diagnostics, info.factor);
                        }
                    }
                }
            }
        }
    }

    private static bool AddUnit(UnitTable table, string safeName, ConfigUnit unit, List<RenderDiagnostic> diagnostics, double prefixFactor = 1.0) {
        var safeUnitName = unit.SingularName;
        var toBaseResult = FormulaConverter.Parse(unit.FromUnitToBaseFunc);
        var fromBaseResult = FormulaConverter.Parse(unit.FromBaseToUnitFunc);

        // WHY: Unit.FromBase falls back to Factor/Offset, which derive from toBase only; a mixed pair must be emitted as two lambdas.
        if ((toBaseResult.Error ?? fromBaseResult.Error) is { } error) {
            diagnostics.Add(new RenderDiagnostic(true, $"{safeName}.{safeUnitName}", error));
            return false;
        }

        var isLinear = toBaseResult.IsLinear && fromBaseResult.IsLinear;
        // WHY: Unit.FromBase relies on toBase's Factor/Offset, so a fromBase formula that is not its inverse would be silently ignored.
        if (isLinear && prefixFactor == 1.0 && !IsInverse(toBaseResult, fromBaseResult)) {
            diagnostics.Add(new RenderDiagnostic(false, $"{safeName}.{safeUnitName}",
                $"FromBaseToUnitFunc is not the inverse of FromUnitToBaseFunc (to base: x*{Number(toBaseResult.Factor)}+{Number(toBaseResult.Offset)}, from base: x*{Number(fromBaseResult.Factor)}+{Number(fromBaseResult.Offset)})"));
        }
        var abbreviations = (unit.Localization?
            .FirstOrDefault(l => l.Culture == "en-US")?.Abbreviations ?? [])
            // WARN: Upstream UnitsNet JSON pre-escapes quotes for its own emitter (e.g. inch: "\\\""); unescape before re-escaping.
            .Select(a => a.Replace("\\\"", "\""))
            // WHY: Some upstream units declare an empty abbreviation (e.g. Ratio.DecimalFraction); it is not a usable key.
            .Where(a => a.Length > 0)
            .ToList();

        string[] scalars = [safeUnitName, unit.PluralName, unit.XmlDocRemarks ?? "", unit.ObsoleteText ?? ""];
        if (scalars.Concat(abbreviations).Any(f => f.IndexOfAny([FieldSeparator, UnitSeparator, ListSeparator]) >= 0)) {
            diagnostics.Add(new RenderDiagnostic(true, $"{safeName}.{safeUnitName}", "contains reserved control characters (U+001D-U+001F)"));
            return false;
        }

        if (!isLinear) {
            table.NonLinear.Add((table.Records.Count, ScaleInput(ToExpression(toBaseResult), prefixFactor), ScaleOutput(ToExpression(fromBaseResult), prefixFactor)));
        }
        table.Factors.Add(isLinear ? toBaseResult.Factor * prefixFactor : 1.0);
        table.Offsets.Add(isLinear ? toBaseResult.Offset : 0.0);

        // Record layout: singular | plural | abbreviations (list-separated) | remarks | obsolete
        string[] record = [
            EscapeCodeString(scalars[0]),
            EscapeCodeString(scalars[1]),
            string.Join(ListSeparatorEscape, abbreviations.Select(a => EscapeCodeString(a))),
            EscapeCodeString(scalars[2]),
            EscapeCodeString(scalars[3])
        ];
        table.Records.Add(string.Join(FieldSeparatorEscape, record));
        return true;
    }

    private static string EscapeCodeString(string? input) {
        return input?
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "")
            .Replace("\n", " ") ?? "";
    }

    private static bool IsInverse(FormulaResult toBase, FormulaResult fromBase) {
        // to: y = a*x + b; from: x = c*y + d  =>  c*a == 1 and c*b + d == 0
        var a = toBase.Factor; var b = toBase.Offset; var c = fromBase.Factor; var d = fromBase.Offset;
        return Math.Abs(c * a - 1) <= 1e-9 && Math.Abs(c * b + d) <= 1e-9 * Math.Max(1.0, Math.Abs(d));
    }

    internal static string Literal(string? input) => $"\"{EscapeCodeString(input)}\"";

    // WHY: Matches UnitsNet naming ("Kilo" + "Meter" -> "Kilometer", "Kilo" + "WattHour" -> "KilowattHour"); case-only, so case-insensitive lookups are unaffected.
    internal static string PrefixedName(string prefix, string name) =>
        string.IsNullOrEmpty(name) ? prefix : prefix + char.ToLowerInvariant(name[0]) + name.Substring(1);

    // WHY: "R" round-trips on every host; "G" truncates to 15 digits under .NET Framework MSBuild (Visual Studio).
    internal static string Number(double value) => value.ToString("R", CultureInfo.InvariantCulture);

    private static readonly Regex ValToken = new(@"\bval\b", RegexOptions.Compiled);

    internal static string ToExpression(FormulaResult r) =>
        r.IsLinear ? $"(val * {Number(r.Factor)} + {Number(r.Offset)})" : $"({r.Lambda})";

    // WHY: A prefixed unit converts as f(x * k) to base, and g(b) / k from base; scaling the output of f is wrong for offsets and non-linear f.
    internal static string ScaleInput(string expression, double prefixFactor) =>
        prefixFactor == 1.0 ? expression : ValToken.Replace(expression, $"(val * {Number(prefixFactor)})");

    internal static string ScaleOutput(string expression, double prefixFactor) =>
        prefixFactor == 1.0 ? expression : $"({expression} / {Number(prefixFactor)})";

    // WHY: Empty metadata must surface as null so consumers can rely on `ObsoleteText is not null`.
    internal static string NullableLiteral(string? input) => string.IsNullOrWhiteSpace(input) ? "null" : Literal(input);
}

/// <summary>
/// A problem found while rendering a quantity; errors skip the unit, warnings keep it.
/// </summary>
internal sealed record RenderDiagnostic(bool IsError, string Unit, string Message);
